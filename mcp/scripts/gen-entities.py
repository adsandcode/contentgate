"""Generate src/entities.ts from Python's own HTML entity tables.

The Python implementation decodes character references with html.unescape.
For the two implementations to count the same characters, the TypeScript side
needs the same 2,231 named references and the same rules for broken numeric
ones, so they are copied from the module Python itself uses rather than from a
second source that could differ.

    python scripts/gen-entities.py      (run from mcp/)

tests/test_entities_table.py fails if the committed file drifts from Python.
"""

import html
import html.entities
import json
import pathlib

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "entities.ts"


def render():
    named = json.dumps(html.entities.html5, ensure_ascii=True, sort_keys=True, indent=0)
    charrefs = json.dumps({str(k): v for k, v in sorted(html._invalid_charrefs.items())},
                          ensure_ascii=True, indent=0)
    codepoints = json.dumps(sorted(html._invalid_codepoints))
    return (
        "// Generated by scripts/gen-entities.py from Python's html.entities.html5 and\n"
        "// the numeric-reference tables in Python's html module. Do not edit by hand.\n\n"
        "export const HTML5_ENTITIES: Record<string, string> = " + named + ";\n\n"
        "export const INVALID_CHARREFS: Record<string, string> = " + charrefs + ";\n\n"
        "export const INVALID_CODEPOINTS: ReadonlySet<number> = new Set(" + codepoints + ");\n"
    )


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print("wrote " + str(OUT))
